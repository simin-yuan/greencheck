#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""x3_strata_rebuild.py — canonical re-derivation of the CI-gate strata.

WHY THIS FILE EXISTS
--------------------
`out/strata_ci.json` (frozen, sha256 e3a77730…) had **no producer script on disk**:
a full-tree search of <redacted-abs-path> for `*.py|*.sh|*.js` referencing `strata_ci` /
`UNDECLARED-KEY` finds only *readers* (`check_readme.py`, `x3_positions.py`);
`annotation_ci` is referenced by no `.py` at all; `annotate.py` has no CI mode; the
session records contain only the write-ups of the results. So the strata file could
not be regenerated by anything. This script closes that gap: it re-derives the strata
from the frozen inputs and is the canonical source for them from now on.

WHAT IS AND IS NOT VERIFIED (read this before quoting any number)
----------------------------------------------------------------
VERIFIED — the *marginals*, because the frozen file carries exactly two:
  * the 13 label totals in `strata_ci["strata"]`, and
  * the 19 per-pair totals in `strata_ci["undeclared_by_pair"]` (plus its total).
NOT VERIFIED — the *per-item* assignment. The original producer is gone, so the only
comparison possible is against marginals, and **identical marginals cannot exclude
swaps of items within one pair between two labels**. `UNDECLARED-KEY` is therefore a
RECONSTRUCTED RULE: `schema_at(root, path) is None`, applied on top of `classify()`.
It reproduces every frozen marginal exactly, which is strong but not independent
evidence that it is the rule the original producer used.

Usage:
    python x3_strata_rebuild.py                # derive, verify, write once
    python x3_strata_rebuild.py --verify-only  # derive + verify, write nothing
"""
from __future__ import annotations
import collections
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

ANNOT_SHA = "5212471b6b6237069872deefe4dcb492b8bac163adadadfaa7fbc2b75e1128ca"
OUT = os.path.join(HERE, "out", "x3_strata_rebuilt.json")

import annotate as A               # UNCHANGED — hash-checked below
from onceio import write_once


def sha256(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def derive():
    """Re-derive the strata. Gate = CI ajv verdicts; label = classify() then the
    UNDECLARED-KEY layer. Returns (items, label_counter, undeclared_by_pair)."""
    res = json.load(open(os.path.join(HERE, "out", "results.json"), encoding="utf-8"))
    ci = json.load(open(os.path.join(HERE, "out", "_xcheck_ci", "ajv.json"),
                       encoding="utf-8"))["results"]
    rows = [r for r in res["rows"] if r.get("mutants_total")]

    items, labels = [], collections.Counter()
    undeclared_pair = collections.Counter()
    for r in rows:
        inst = os.path.join(A.REPO, r["instance"].replace("/", os.sep))
        txt = open(inst, encoding="utf-8").read()
        orig = json.loads(txt)
        schema = json.load(open(os.path.join(A.SCHEMAS, r["schema"]), encoding="utf-8"))
        for name, patch in A.gm.build_mutants({"instance.json": txt}):
            content = next(iter(patch.values()))
            if content is None:
                continue
            try:
                mut = json.loads(content)
            except Exception:
                continue
            if ci.get(r["schema"], {}).get(name) != "release":
                continue
            if mut == orig:
                continue                       # no-op: not an escape
            changes = [c for c in A.diff(orig, mut)
                       if c[1] in ("removed", "changed", "arrayshrunk", "added")]
            if not changes:
                p, kind, label = None, None, "no-detectable-change"
            else:
                changes.sort(key=lambda c: (len(c[0]), str(c[0])))
                p, kind = changes[0]
                try:
                    o = A.value_at(orig, p) if kind != "removed" else None
                except Exception:
                    o = None
                m = A.value_at(mut, p) if kind != "removed" else None
                label = A.classify(schema, p, kind, o, m)
            node = A.schema_at(schema, tuple(p)) if p else None
            if node is A.UNRESOLVED:
                node = None
            if p and node is None:
                label = "UNDECLARED-KEY"
            labels[label] += 1
            if label == "UNDECLARED-KEY":
                undeclared_pair[r["schema"]] += 1
            items.append({"pair": r["schema"], "name": name, "label": label,
                          "path": list(p) if p is not None else None})
    return items, labels, undeclared_pair


def main():
    verify_only = "--verify-only" in sys.argv[1:]
    got = sha256(os.path.join(HERE, "annotate.py"))
    print("annotate.py sha256 :", got)
    if got != ANNOT_SHA:
        raise SystemExit("STOP: annotate.py changed since it was recorded")

    frozen = json.load(open(os.path.join(HERE, "out", "strata_ci.json"), encoding="utf-8"))
    items, labels, undeclared_pair = derive()

    bad_labels = {k: [labels.get(k, 0), frozen["strata"].get(k, 0)]
                  for k in set(labels) | set(frozen["strata"])
                  if labels.get(k, 0) != frozen["strata"].get(k, 0)}
    bad_pairs = {k: [undeclared_pair.get(k, 0), frozen["undeclared_by_pair"].get(k, 0)]
                 for k in set(undeclared_pair) | set(frozen["undeclared_by_pair"])
                 if undeclared_pair.get(k, 0) != frozen["undeclared_by_pair"].get(k, 0)}
    if bad_labels or bad_pairs:
        print("STOP: rebuilt strata do not match out/strata_ci.json")
        for k, v in bad_labels.items():
            print(f"   label {k!r}: rebuilt={v[0]} frozen={v[1]}")
        for k, v in bad_pairs.items():
            print(f"   pair  {k!r}: rebuilt={v[0]} frozen={v[1]}")
        raise SystemExit(1)
    print(f"marginals OK: {len(labels)} labels + {len(undeclared_pair)} per-pair "
          f"counts equal out/strata_ci.json (items={len(items)}, "
          f"undeclared_key={labels['UNDECLARED-KEY']})")

    # internal cross-check against the already-frozen per-item positions file, if present
    cross = {"file": "out/x3_positions.json", "present": False, "items_equal": None}
    pos = os.path.join(HERE, "out", "x3_positions.json")
    if os.path.exists(pos):
        pj = json.load(open(pos, encoding="utf-8"))
        mine = {(i["pair"], i["name"]): i["label"] for i in items}
        theirs = {(i["pair"], i["name"]): i["label"] for i in pj["items"]}
        cross["present"] = True
        cross["items_equal"] = (mine == theirs)
        print("cross-check vs out/x3_positions.json: per-item labels equal =",
              cross["items_equal"],
              "(both derive from the same re-implementation — weak evidence, stated as such)")

    if verify_only:
        print("--verify-only: nothing written")
        return

    summary = {
        "what": "canonical re-derivation of the CI-gate strata",
        "provenance": "the original producer of out/strata_ci.json was not found on disk "
                      "or in the records (full-tree grep + session search, 2026-10-11); this "
                      "script re-derives the strata from the frozen inputs",
        "gate": {"annotate_py_sha256": got, "annot_py_unchanged": True,
                 "ci_released": frozen["ci_released"]},
        "verified": {
            "label_totals": len(labels),
            "undeclared_per_pair_totals": len(undeclared_pair),
            "marginals_equal_to_strata_ci": True,
        },
        "not_verified": {
            "per_item_assignment": "cannot be checked: the original producer is gone, and "
                                   "equal marginals cannot exclude swaps of items within one "
                                   "pair between two labels",
            "undeclared_key_rule": "RECONSTRUCTED as schema_at(root, path) is None on top of "
                                   "classify(); every frozen marginal is reproduced, which is "
                                   "strong but not independent evidence",
        },
        "cross_check_vs_x3_positions": cross,
        "items": len(items),
        "strata": dict(labels.most_common()),
        "undeclared_by_pair": dict(undeclared_pair.most_common()),
    }
    print(json.dumps({k: v for k, v in summary.items() if k != "items"},
                     ensure_ascii=False, indent=1))
    write_once(OUT, {"summary": summary, "items": items})
    print("wrote out/x3_strata_rebuilt.json (write-once)")


if __name__ == "__main__":
    main()
